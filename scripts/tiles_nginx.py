#!/usr/bin/env python3
"""Generate the nginx tile origin (L2 cache + archive) from config/apis.toml [tiles].

The worker (preview/src/tiles.js) calls
  {origin}/tiles/{policy}/{source}/{date|-}/{z}/{x}/{y}
with the shared key header; nginx maps that to the entry's url_template and keeps
the answer in the zone the policy names. The key lives in secrets.local.toml and in
a root-only snippet outside the repo, never in the generated site file.

  tiles_nginx.py --print            show the site conf
  tiles_nginx.py --install          write conf + key snippet, nginx -t, reload
"""
from __future__ import annotations

import argparse
import os
import re
import secrets
import subprocess
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from termalwave.providers.registry import load_apis_config, tile_cache_policy  # noqa: E402
from termalwave.providers.secrets import load_credentials  # noqa: E402

SECRETS = ROOT / "config" / "secrets.local.toml"
SITE_NAME = "termalwave-origin"
SITES_AVAILABLE = Path("/etc/nginx/sites-available")
SITES_ENABLED = Path("/etc/nginx/sites-enabled")
KEY_SNIPPET = Path("/etc/nginx/snippets/termalwave-origin-key.conf")
REALIP_SNIPPET = Path("/etc/nginx/snippets/cloudflare-realip.conf")

DATE_RE = r"(?<tw_date>\d{4}-\d{2}-\d{2})"
TILE_RE = r"(?<tw_z>\d{1,2})/(?<tw_x>\d{1,7})/(?<tw_y>\d{1,7})"
PLACEHOLDERS = {"{z}": "$tw_z", "{x}": "$tw_x", "{y}": "$tw_y", "{date}": "$tw_date"}


def header_var(header: str) -> str:
    return "$http_" + header.lower().replace("-", "_")


def upstream_url(source: str, template: str, api_key: str | None = None) -> str:
    url = template
    for ph, var in PLACEHOLDERS.items():
        url = url.replace(ph, var)
    leftover = re.findall(r"\{[^}]*\}", url)
    if leftover:
        raise SystemExit(f"{source}: unsupported placeholders {leftover} in url_template")
    if api_key:
        # key stays in the generated nginx conf (root-only site); never in app-config
        sep = "&" if "?" in url else "?"
        url = f"{url}{sep}api_key={api_key}"
    return url


def source_policies(entry: dict, policy: str) -> list[str]:
    """Origin paths a source answers on; dated archives also get the short-lived recent path."""
    if policy == "archive" and "{date}" in str(entry["url_template"]):
        return ["archive", "recent"]
    return [policy]


def location(source: str, entry: dict, path_policy: str, tiles: dict, credentials: dict[str, str]) -> str:
    pol = tiles["policies"][path_policy]
    zone = tiles["zones"][pol["zone"]]["name"]
    tmpl = str(entry["url_template"])
    date = DATE_RE if "{date}" in tmpl else "-"
    key_name = str(entry.get("upstream_api_key") or "").strip()
    api_key = credentials.get(key_name, "").strip() if key_name else ""
    if key_name and not api_key:
        raise SystemExit(f"{source}: missing credential {key_name} in secrets.local.toml / env")
    return f"""
    location ~ "^{tiles['route']}/{path_policy}/{source}/{date}/{TILE_RE}$" {{
        proxy_cache {zone};
        proxy_cache_valid 200 {pol['origin_valid']};
        proxy_cache_valid 404 {tiles['negative_valid']};
        proxy_pass {upstream_url(source, tmpl, api_key or None)};
    }}"""


def render(apis: dict, credentials: dict[str, str] | None = None) -> str:
    tiles = apis["tiles"]
    basemaps = apis.get("basemaps") or {}
    entries = basemaps.get("entries") or {}
    root = tiles["cache_root"].rstrip("/")
    credentials = credentials if credentials is not None else load_credentials(ROOT, apis)

    zones = "\n".join(
        f"proxy_cache_path {root}/{key} levels=1:2 keys_zone={z['name']}:{z['keys_mb']}m "
        f"inactive={z['inactive']} max_size={z['max_size']} use_temp_path=off;"
        for key, z in tiles["zones"].items()
    )

    locations: list[str] = []
    for source in basemaps.get("list") or []:
        entry = entries.get(source)
        if not entry:
            continue
        policy = tile_cache_policy(entry)
        if policy == "direct":
            continue
        for path_policy in source_policies(entry, policy):
            locations.append(location(source, entry, path_policy, tiles, credentials))

    return f"""# generated by scripts/tiles_nginx.py from config/apis.toml [tiles]; edit the config, not this file
{zones}

# defines $tw_origin_key_ok from {tiles['key_header']}; root-only, written by the same script
include {KEY_SNIPPET};

server {{
    listen 80;
    listen [::]:80;
    server_name {tiles['origin_host']};

    include {REALIP_SNIPPET};
    access_log /var/log/nginx/{SITE_NAME}.access.log;

    # only the worker holds the key; cloudflare flexible ssl talks to us on :80
    if ($tw_origin_key_ok = 0) {{
        return 403;
    }}

    resolver {tiles['resolver']} valid=300s ipv6=off;
    resolver_timeout 5s;

    proxy_http_version 1.1;
    proxy_ssl_server_name on;
    proxy_connect_timeout 5s;
    proxy_read_timeout 30s;
    proxy_set_header Connection "";
    proxy_set_header Cookie "";
    proxy_set_header Authorization "";
    proxy_set_header {tiles['key_header']} "";
    proxy_set_header User-Agent "{tiles['user_agent']}";

    proxy_cache_key $uri;
    proxy_cache_lock on;
    proxy_cache_lock_timeout 20s;
    proxy_cache_background_update on;
    proxy_cache_use_stale error timeout updating invalid_header http_429 http_500 http_502 http_503 http_504;
    proxy_ignore_headers Cache-Control Expires Set-Cookie Vary X-Accel-Expires X-Accel-Buffering;
    proxy_hide_header Set-Cookie;
    proxy_hide_header Cache-Control;
    proxy_hide_header Expires;
    add_header X-Cache-Status $upstream_cache_status always;
{''.join(locations)}

    location / {{
        return 404;
    }}
}}
"""


def key_snippet(header: str, key: str) -> str:
    return (
        "# generated by scripts/tiles_nginx.py; secret, keep root-only\n"
        f"map {header_var(header)} $tw_origin_key_ok {{\n"
        "    default 0;\n"
        f'    "{key}" 1;\n'
        "}\n"
    )


def load_or_create_key(name: str) -> str:
    text = SECRETS.read_text()
    cf = tomllib.loads(text).get("cloudflare") or {}
    if cf.get(name):
        return str(cf[name])
    if "[cloudflare]" not in text:
        raise SystemExit(f"{SECRETS.name}: [cloudflare] section missing")
    key = secrets.token_urlsafe(32)
    text = text.replace("[cloudflare]\n", f'[cloudflare]\n{name} = "{key}"\n', 1)
    SECRETS.write_text(text)
    print(f"{name} generated in {SECRETS.relative_to(ROOT)} [cloudflare]")
    return key


def write_private(path: Path, body: str) -> None:
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "w") as fh:
        fh.write(body)
    os.chmod(path, 0o600)


def install(apis: dict) -> int:
    tiles = apis["tiles"]
    key = load_or_create_key(tiles["key_secret"])
    write_private(KEY_SNIPPET, key_snippet(tiles["key_header"], key))

    for zone in tiles["zones"]:
        path = Path(tiles["cache_root"]) / zone
        path.mkdir(parents=True, exist_ok=True)
        subprocess.run(["chown", "www-data:www-data", str(path)], check=True)

    site = SITES_AVAILABLE / SITE_NAME
    site.write_text(render(apis))
    link = SITES_ENABLED / SITE_NAME
    if not link.exists():
        link.symlink_to(site)

    test = subprocess.run(["nginx", "-t"], capture_output=True, text=True)
    if test.returncode != 0:
        print(test.stderr, file=sys.stderr)
        return 1
    subprocess.run(["systemctl", "reload", "nginx"], check=True)
    print(f"{site} installed, nginx reloaded")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--print", action="store_true", help="print the site conf")
    mode.add_argument("--install", action="store_true", help="write conf + key, nginx -t, reload")
    args = ap.parse_args()

    apis = load_apis_config(ROOT)
    if args.print:
        sys.stdout.write(render(apis))
        return 0
    return install(apis)


if __name__ == "__main__":
    raise SystemExit(main())
