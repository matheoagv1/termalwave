const NUM = (n: number, d = 0): string =>
  n.toLocaleString("en-US", { minimumFractionDigits: d, maximumFractionDigits: d });

const bareUnit = (unit: string): boolean => unit === "índice" || unit === "index" || unit === "";

export const F = {
  num: NUM,
  value: (v: number | null, unit: string, d = 0): string | null =>
    v == null ? null : bareUnit(unit) ? NUM(v, d) : `${NUM(v, d)} ${unit}`,
  delta: (dv: number, unit: string, d = 0): string => {
    const s = dv > 0 ? "+" : "\u2212";
    const a = NUM(Math.abs(dv), d);
    return bareUnit(unit) ? `${s}${a}` : `${s}${a} ${unit}`;
  },
  bytes: (b: number): string => (b >= 1e6 ? `${NUM(b / 1e6, 1)} MB` : `${NUM(Math.round(b / 1e3))} KB`),
  lat: (v: number): string => `${NUM(Math.abs(v), 2)}° ${v < 0 ? "S" : "N"}`,
  lon: (v: number): string => `${NUM(Math.abs(v), 2)}° ${v < 0 ? "W" : "E"}`,
  year: (iso: string): string => iso.slice(0, 4),
};

